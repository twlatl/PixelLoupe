#!/bin/zsh
# Writes the service API credentials PixelLoupe signs requests with as Swift source, XOR-masked so they don't sit in
# the binary as plain strings. Run by the PixelLoupe target's Generate Secrets build phase; the masking only stops
# casual extraction (docs/adr/0001-embedded-service-secrets.md).
#
# Each value comes from the environment (the release workflow sets FLICKR_KEY and FLICKR_SECRET from repository
# secrets), else from .env at the repository root (see .env.example). Without them the app builds with empty values,
# and the services that need them say they're unavailable. Only these names are read from .env: it also holds the
# release secrets Scripts/setup-release-secrets.sh saves, which must never reach the app.
#
#   Scripts/generate-secrets.sh <output.swift>

set -euo pipefail

output=${1:?usage: generate-secrets.sh <output.swift>}
env_file=${0:A:h:h}/.env

# Build setting-style name → Swift property name.
typeset -A properties=(FLICKR_KEY flickrKey FLICKR_SECRET flickrSecret)

# The value of $1: from the environment, else the last `NAME=value` line in .env (quotes around the value removed).
value() {
  if [[ -n ${(P)1:-} ]]; then
    print -rn -- ${(P)1}
  elif [[ -r $env_file ]]; then
    local line=$(grep -E "^[[:space:]]*(export[[:space:]]+)?$1=" $env_file | tail -n 1)
    line=${line#*=}
    line=${line%%[[:space:]]#}
    [[ $line == \"*\" || $line == \'*\' ]] && line=${line[2,-2]}
    print -rn -- $line
  fi
}

# The bytes of stdin as a Swift array literal's elements.
bytes() { od -An -v -tu1 | tr -s ' \n' '  ' | sed -E 's/^ +//; s/ +$//; s/ /, /g' }

source="// Generated by Scripts/generate-secrets.sh at build time. Don't edit or commit.

nonisolated extension Secrets {"
for name in ${(ko)properties}; do
  plain=($(value $name | bytes | tr -d ,))
  # The mask is derived from the value, so the output (and the build) only changes when a value does.
  mask=($(value $name | shasum -a 256 | cut -c1-64 | xxd -r -p | bytes | tr -d ,))
  masked=()
  for (( i = 1; i <= ${#plain}; i++ )); do
    masked+=$(( plain[i] ^ mask[(i - 1) % ${#mask} + 1] ))
  done
  (( ${#plain} )) || mask=()
  source+="
    static let ${properties[$name]} = reveal([${(j:, :)masked}], mask: [${(j:, :)mask}])"
done
source+="
}
"

# Rewrite only on a change, so an unchanged value doesn't recompile and relink the app.
if [[ ! -f $output || "$(<$output)"$'\n' != $source ]]; then
  mkdir -p ${output:h}
  print -rn -- $source > $output
fi
